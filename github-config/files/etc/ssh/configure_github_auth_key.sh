#!/bin/sh
set -eu

SSH_KEY_FILE=${SSH_KEY_FILE:-/etc/ssh/github_key.pub}
SSH_CONFIG_FILE=${SSH_CONFIG_FILE:-/etc/ssh/ssh_config.d/99-github.conf}

fail() {
    printf '[github-config] %s\n' "$*" >&2
    exit 1
}

ret() {
    printf '[github-config] %s\n' "$*"
    exit 0
}

# Github part
github_user=$(gh api user --jq .login)
github_keys=$(curl -fsSL "https://github.com/$github_user.keys") ||
    fail "unable to fetch GitHub SSH authentication keys for $github_user."

# The recovery steps below run on the HOST, where $SANDBOX_NAME does not
# exist -- it is a sandbox-only variable. Resolve the name here and print its
# value, so the user can paste the command instead of substituting by hand.
name=${SANDBOX_NAME:-$(hostname 2>/dev/null || true)}
[ -n "$name" ] || name="<sandbox-name>"

# Same recovery preamble for every "the agent is not answering" state: the
# forwarding setting first (it is the one cause that survives every restart),
# then the host agent's keys, then the container restart.
recover="On the HOST: 1) 'sbx settings get ssh.agentForwardingEnabled' must print true -- if it does not, 'sbx settings set ssh.agentForwardingEnabled true' and then 'sbx daemon restart', because a changed setting only reaches sandboxes that already exist once the daemon has restarted; 2) 'ssh-add -l' must list your key, else 'ssh-add ~/.ssh/id_ed25519'; 3) from that same shell, restart this sandbox: 'sbx stop $name' then 'sbx run --name $name'."

sock=${SSH_AUTH_SOCK:-}

if [ -z "$sock" ]; then
    fail "SSH_AUTH_SOCK is not set." \
         "Sandboxes export it unconditionally, so something in this shell unset it."
fi

# SSH_AUTH_SOCK is baked into every sandbox whether or not forwarding was
# wired, so its presence proves nothing. The socket's existence is the real
# check, and it separates "no relay at all" from "something is listening but
# not answering" -- states that read very differently in the error message.
if [ ! -S "$sock" ]; then
    fail "the forwarded agent socket $sock does not exist. $recover"
fi

if agent_keys=$(ssh-add -L 2>&1); then
    rc=0
else
    rc=$?
fi

# ssh-add exit 2 is "could not connect at all"; exit 1 is "connected, but
# the exchange failed or the agent is empty". Forwarding being switched off
# can land in either one depending on how far the connection gets, so only
# the genuinely-empty agent gets a recovery of its own -- every other state
# runs the same host-side checks, the forwarding setting first.
case $rc in
    0) ;;
    1)
        case "$agent_keys" in
            *"no identities"*)
                ret "the forwarded agent holds no keys (ssh-add: $agent_keys)." \
                     "Run 'ssh-add ~/.ssh/id_ed25519' there, then 'sbx stop $name' and 'sbx run --name $name' from that same shell."
                ;;
            *) fail "the agent did not answer usably (ssh-add: $agent_keys). $recover" ;;
        esac
        ;;
    *) fail "nothing is accepting connections on $sock (ssh-add: $agent_keys, exit $rc). $recover" ;;
esac

# Match public keys (type + key data).
matches=$(
    while IFS= read -r agent_key; do
        [ -z "$agent_key" ] && continue

        read -r agent_type agent_data _ <<EOF
$agent_key
EOF

        while IFS= read -r github_key; do
            [ -z "$github_key" ] && continue

            read -r github_type github_data _ <<EOF
$github_key
EOF

            if [ "$agent_type" = "$github_type" ] && [ "$agent_data" = "$github_data" ]; then
                echo "$agent_type $agent_data"
                break
            fi
        done <<EOF
$github_keys
EOF
    done <<EOF
$agent_keys
EOF
)

matches=$(echo "$matches" | sort -u)
match_count=$(echo "$matches" | grep -c . || true)

case "$match_count" in
    1) ;;
    0) ret "no matching GitHub key found in ssh-agent. nothing to do." ;;
    *) fail "N=$match_count GitHub authentication keys found in ssh-agent." ;;
esac

echo "$matches" >"$SSH_KEY_FILE"
echo "SSH identity for GitHub account ($github_user) stored at $SSH_KEY_FILE."

cat >"$SSH_CONFIG_FILE" <<EOF
# Automatically generated by $(readlink -f "$0")
Host github.com
    User git
    IdentityFile "$SSH_KEY_FILE"
    IdentitiesOnly yes
EOF

# Testing Github SSH authentication
# (Command always exits with 1 but message differs between success and failure)
ssh_output=$(ssh -T -o BatchMode=yes git@github.com 2>&1) || true
if printf '%s\n' "$ssh_output" | grep -qE "^Hi $github_user! You've successfully authenticated\b"; then
    ret "GitHub SSH authentication successful for $github_user."
else
    fail "GitHub SSH authentication failed for $github_user (ssh output: $ssh_output)."
fi
